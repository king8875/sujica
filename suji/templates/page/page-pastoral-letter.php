			<p>그리스도의 평화가 여러분과 함께하기를 빕니다. 우리는 수년간에 걸친 코로나 감염병 위기를 뒤로하고 새로운 출발점 위에 서 있습니다. 코로나19는 우리 사회뿐 아니라 교회에도 큰 타격을 주었습니다. 이 위기를 지혜롭게 극복하고자 지난 사목교서에서는 ‘일상중심의 신앙실천’과 ‘자기주도적 신앙실천’을 제안하였고, 교구민 여러분의 적극적인 참여로 우리 교구는 길었던 코로나 위기를 이겨내고 일상으로 돌아올 수 있었습니다. 비록 예전의 상태를 회복하려면 아직도 더 많은 시간과 노력이 필요하지만, 하느님의 은총과 교구민 여러분의 적극적인 참여로 이 시련을 충분히 이겨낼 수 있다고 확신합니다.</p>

			<p>지난 2023년은 교구 설정 60주년을 맞는 해였습니다. 이 뜻깊은 해를 맞아 우리 교구는 오늘의 복음화 현실을 새롭게 진단하고, 이에 부합하여 교구의 선교 사명을 새롭게 하려는 의도로 지난 2018년 개편된 대리구 제도를 다각적으로 검토하였습니다. 새로운 대리구 제도와 교구 편제가 시행되면서 크고 작은 어려움을 겪고는 있지만, 비대해진 교구를 효과적으로 운영하고, 친교와 소통을 바탕으로 전 교구민이 능동적으로 교회의 선교 복음화 사명에 참여하는 데에 매우 효과적인 제도임을 새롭게 인식할 수 있었습니다. 특히 새로운 대리구 제도에 담긴 ‘통합사목’이 현재 보편교회에서 추진하고 있는 시노드 정신을 실현하는 교회 쇄신의 노력과 일맥상통함을 확인할 수 있었습니다.</p>

			<p>통합사목은 교회 내 모든 구성원의 ‘유기적 협력’을 그 원동력으로 삼고 있습니다. 앞으로 계속하여 통합사목을 기반으로 지구 중심 사목과 연합 사목이 상호 연속성을 가지고 교구 사목정책의 큰 이정표가 될 수 있도록 구성원 모두가 역량을 모을 수 있기를 희망합니다.</p>

			<p>이러한 배경에서 저는 향후 3년간 우리 수원교구의 모든 구성원이 그리스도를 머리로 한 몸을 이룬 지체로서 교회의 선교 사명에 각별한 관심과 책임의식을 가지고, 시노드 정신에서 영감을 얻는 통합사목을 향해 중점적으로 노력해야 할 사항을 말씀드리고자 합니다.</p>
