			<p>통합사목을 실현하기 위해 가장 시급한 대상으로 떠오르는 것은 ‘생태’입니다. 통합사목 차원에서 우리는 모두 생태적 회개로 초대되고 있습니다. 2015년 프란치스코 교황님께서는 생태회칙 「찬미받으소서」(Laudato Si’)를 반포함으로써 인류에게 환경 위기에 대한 경각심을 불러일으키셨습니다. 나아가 교황님께서는 현재의 “생산방식과 소비방식을 그대로 유지할 경우, 부정적인 영향들이 더욱 강화될 것”이며 종말이라는 말을 무시할 수 없을 정도로 상황이 심각함을 경고하셨습니다. 우리는 이제 지속 가능한 사회로의 전환을 위해 성장 중심의 가치관을 버리고 생명 중심의 삶으로 전환하여야 합니다. 그러기 위해 우리는 우리 사회의 성장 담론이 우리 삶에 어떤 영향을 주고 있는지 근본적으로 성찰해야 합니다. 그리하여 세상 태초부터 하느님께서 우리에게 세상의 온갖 것을 다스리도록 부여해 주신 창조질서 보전에 관한 바른 의미를(창세 1,25-26 참조) 되새기는 가운데 생태적 회개를 이루어야 합니다.</p>

			<p>예수님께서는 여러 가지 방법으로 하느님에게서 멀어진 이들과, 가난한 이들같이 공동체에서 외면당하는 이들에게 특별한 관심을 보이십니다. 기후와 환경의 위기로 가장 먼저 피해를 받고 고통을 당하게 될 사람들은 바로 가난하고 힘없는 사회적 약자들입니다. 우리가 「찬미받으소서」 7년 여정뿐 아니라 앞으로도 계속해서 기후 위기에 맞서고 지속 가능한 사회로의 전환을 위해 노력하는 모든 일은 예수님께서 가난한 이들과 함께하시려는 마음에 동참하는 것이라 하겠습니다.</p>

			<p>우리 교구는 지난 2021년 찬미받으소서 7년 여정을 시작하며 2040년까지 탄소중립을 이루기 위해 ‘탄소중립 선포 미사’를 거행했습니다. 이 여정에 발맞춰, 생태적 회개를 위해 앞으로 3년간 우리 교구 구성원들이 공동의 집 지구를 위해 기도하며, 본당과 각 기관 그리고 가정에서 다음과 같은 일을 실천해 주시기를 당부드립니다.</p>

			<ol class="pl-plan">
				<li><span class="pl-year">2024년</span>에는 우리 가정, 교회공동체, 사회의 생태 의식의 현주소 진단하기</li>
