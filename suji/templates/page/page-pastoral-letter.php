			<h2 class="pl-heading"><span class="pl-num">Ⅴ</span>통합사목의 주요 대상 &ndash; 청소년</h2>

			<p>우리는 제16차 세계주교시노드 여정에 참여하는 한국 교회가 대륙별 회기를 마무리하기 위해 제출한 ‘종합 의견서’에서 이 시대의 청소년들 역시 가난하고 힘없는 여정의 동반자들임을 확인하게 되었습니다. 이와 같은 맥락에서 우리 교구가 앞으로 나아가야 할 사목정책의 기본틀이 되는 통합사목의 대상에서 청소년들이 그 예외가 될 수 없습니다.</p>

			<p>교회는 신앙생활에 참여하는 청소년들이 감소하는 현상을 겪으며 교회의 미래에 대한 고민이 깊어지고 있습니다. 저는 이미 오래전부터 요구되고 있는 젊은이들에 대한 사목적 관심과 노력이 필요하다는 의견에 전적으로 공감합니다. 우리는 무엇보다 먼저 청소년들의 고민을 경청하고 그들이 원하는 것이 무엇인지를 알아야 합니다. 이로써 그들에게 필요한 자리를 마련해야 합니다. 교회가 지난 제15차 세계주교시노드 여정과 그 결실인 교황님의 권고 「그리스도는 살아 계십니다」를 망각하고 있는 것은 아닌지 자문하게 됩니다. 교회는 청소년들이 단순히 사목 대상이 아니라 복음선포의 주역임을 알고 있습니다. 청소년들이 그들의 방법으로 복음을 살고 선포하는 주역이 되도록 교회는 그들을 응원하고 동반할 것입니다.</p>

			<p>프란치스코 교황님께서는 2023년 8월 6일 포르투갈 리스본에서 열린 제37차 세계청년대회 파견 미사에서, 4년 뒤인 2027년 세계청년대회는 아시아, 곧 대한민국 서울에서 열린다고 발표하셨습니다. 2027년 서울에서 열리는 세계청년대회를 통해 우리 청소년들이 자신이 가지고 있는 가톨릭 신앙이 우리나라에만 국한된 것이 아니라, 유럽의 서쪽 끝에서 우리나라에 이르기까지 보편된 신앙임을 더욱 깊이 느낄 수 있는 기회가 되기를 희망합니다. 나 홀로 이 신앙을 지키고 살아가려는 것이 아니라, 나와 동행하는 이들이 전 세계에 있음을 체험하는 일은 청소년들에게 큰 위로와 힘이 될 것입니다.</p>

			<p>이번 제38차 세계청년대회는 분명 통합사목을 기조로 청소년들을 향한 사목에 정진하려는 우리에게 하느님께서 주신 소중한 기회입니다. 세계청년대회를 준비하는 시간 안에서 청소년들을 향한 우리의 관심에 새로운 활력을 얻을 수 있기를 기대합니다. 그래서 저는 다음과 같은 청소년 사목의 실천적인 방향을 제안합니다.</p>

			<ol class="pl-plan">
				<li><span class="pl-year">2024년</span> 믿음의 순례자인 청소년들의 의견을 경청하기</li>
				<li><span class="pl-year">2025년</span> 희망의 순례자인 청소년들의 걸음에 동행하기</li>
				<li><span class="pl-year">2026년</span> 사랑의 순례자인 청소년들 각자의 성소 식별을 통한 사랑의 여정에 함께하기</li>
