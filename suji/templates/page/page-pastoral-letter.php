			<h2 class="pl-heading"><span class="pl-num">Ⅲ</span>통합사목의 실천 원리 &ndash; 영적 체질개선</h2>

			<p>통합사목은 영적 체질개선을 통해 이루어집니다. 통합사목의 실천 원리인 영적 체질개선을 위해 지금 우리 공동체에 부족한 것은 무엇이며, 가장 필요한 일은 무엇인지 먼저 알아야 합니다. 공동체의 고른 성장을 목표로 삼는 통합사목은 그 실행과정에서 유기적 협력이 바탕이 되어야 합니다. 우리 공동체가 성장 조건을 갖추었다 하더라도 내부에 여전히 결핍되고 막힌 부분이 있거나 그 상태가 장기간 지속될 경우, 균형 잡힌 단계로 진입하지 못한 채 기존의 편중된, 곧 지금 잘되고 있는 사목에만 집중하는 일을 계속해서 반복한다면 전체적으로 ‘발육 부진’의 상태를 벗어나기 어렵게 됩니다. 이를 극복하기 위해 우선적 돌봄의 대상이 누구이고 결핍된 요소는 무엇인지(최소치 사목), 나아가 공동체의 고유한 영적 자산을 발굴하고, 유능한 부분을 살릴 수 있는 동력이 무엇인지 식별할 필요가 있습니다(최대치 사목). 이어서 구성원의 합의와 상호 협력으로 이끄는 실행이 뒷받침되어야 합니다. 우리 교구가 결연한 의지로 실천에 옮기려는 통합사목은 한마디로 교회 쇄신 차원에서 신앙의 수많은 유기적 지체들, 예를 들어 소공동체, 본당, 지구, 대리구, 교구로 이루어진 공동체 자신이 결핍된 요소를 스스로 돌보고 성장시킴으로써 공동체가 균형 있게 성장할 수 있도록 이끌어 나가는 것입니다. 이러한 노력이 바로 영적 체질개선입니다.</p>

			<p>영적 체질개선을 위한 토양을 우리는 복음의 기쁨에서 찾아야 합니다. 복음과 신앙의 핵심은 언제나 기쁨입니다. 말 그대로 복음은 ‘기쁜 소식’이기 때문입니다. 복음을 통해 예수님과 함께하며 맛본 기쁨의 체험은 신앙인 자신을 내적으로 성장하게 하고, 다른 이들과 그 기쁨을 나누고 싶은 마음을 불러일으킵니다. 복음을 선포하도록 우리를 다그치는 것은 그리스도의 사랑입니다(2코린 5,14 참조). 진정한 기쁨은 다른 이들과 세상으로 확장되면서 더 깊어집니다. 그런데 우리가 그 기쁨을 제대로 느끼지 못하고 알지 못한다면 어떻게 그 기쁨을 다른 이에게 전할 수 있겠습니까? 복음화라는 사명의 수행은 강요나 강제하는 방식이 아니라 초대하는 방식을 통해서 이루어집니다.</p>

			<blockquote class="pl-quote">
				<p>그리스도인은 새로운 의무를 강요하는 사람이 아니라 기쁨을 나누는 사람, 아름다운 전망을 보여 주는 사람, 그리고 풍요로운 잔치에 다른 이들을 초대하는 사람입니다. 교회가 성장하는 것은 개종 강요가 아니라 ‘매력’ 때문입니다.</p>
				<cite>프란치스코 교황, 「복음의 기쁨」 14항</cite>
