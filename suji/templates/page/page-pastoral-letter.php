			<h2 class="pl-heading"><span class="pl-num">Ⅱ</span>통합사목을 위한 기본원리 &ndash; 시노달리타스(synodalitas)</h2>

			<p>보편교회는 2021년 10월부터 2024년 10월까지 ‘시노드 정신을 살아가는 교회를 위하여 : 친교, 참여, 사명’을 주제로 제16차 세계주교시노드 여정을 보내고 있습니다. 프란치스코 교황님께서는 이번 세계주교시노드를 시작하면서, 특별히 미래를 향한 우리의 비전이 시노드적인 교회에 있음을 강조하셨습니다. 시노드적 교회란 하느님 백성이 함께 걸으며 구성원 전체(성직자, 수도자, 평신도)가 교회의 복음화 사명에 능동적으로 참여하는 과정에서 자신을 친교로 드러내는 교회를 의미합니다. 친교, 참여, 사명은 시노드 정신을 살아가는 교회가 추구하는 중심 가치입니다. 시노달리타스의 기초는 세례받은 모든 신자가 그리스도의 몸을 이루는 지체로서(1코린 12,27 참조) 부여받은 공통된 품위와 사명과 은사를 인정하고 동행하는 데 있습니다.</p>

			<p>한국 교회는 “제16차 세계주교시노드 정기총회 한국 교회 종합 의견서”에서 시노드의 여정 중에 함께 걸어가야 하는 동반자로서 동반자적 인식과 믿음의 부족이 경청의 부족으로 이어진다고 진단하였습니다. 이러한 진단은 우리가 서로를 동반자로 인식하며 서로에게 경청하고 서로를 신뢰하고 있는지를 묻게 합니다. 모든 그리스도인은 근본적으로 동등한 품위를 지니며, 형제적 친교 안에서 예수 그리스도를 증언하고 선포하는 사명을 함께 수행합니다. 이는 성직자와 수도자와 평신도가 그리스도를 증언하고 진리에 봉사하는 데에서 모두가 능동적이며 책임 있는 주체임을 의미합니다. 물론 교회의 모든 활동에서 ‘주인’은 교회를 살게 하시고 복음을 선포하게 하시며, 예수님을 그리스도라 고백하게 하시고 하느님을 ‘아빠, 아버지’라고 부르게 하시는 ‘성령’이시며, 우리는 능동적이고 책임 있는 주체로서 각자의 방식으로 성령의 활동에 참여합니다. 그렇기에 우리는 성령께서 이끄시는 여정을 함께 걷는 동반자로서 서로 신뢰하고 경청하도록 초대받고 있습니다. 이를 위해 우리는 혐오와 배제의 유혹을 넘어, 우리 안에 존재하는 차이와 다름을 인정하고 다양성 안에서 일치할 수 있도록 인내를 청해야 할 것입니다.</p>

			<p>한편은 많은 것을 가지고 있고 다른 한편에는 부족한 것이 있을 때, 많은 것을 가진 쪽에서 부족한 쪽을 채운다면 함께 풍요로워질 것입니다. 우리는 이러한 보조성의 원리에 따라 운영되는 통합사목의 기본 취지가 시노달리타스에 담긴 교회 쇄신의 의지와 같은 원의(願意)를 가지고 있음을 발견하게 됩니다. 아울러 시노드 정신을 살아가는 교회의 정신이 2018년부터 시행되고 있는 새로운 대리구 제도와 교구 편제 개정에 담겨 있음을 확인하게 됩니다. 이러한 정신에서 교구 내 모든 구성원은 공통된 품위와 사명 안에서 서로의 의견을 경청하고, 동반하며 식별하는 과정을 통해 서로 보완하고, 함께 교회 사명에 참여하며 살아가려는 상보상생(相補相生)의 길을 가도록 요청받고 있습니다. 시노드 정신의 도움으로 우리는 통합사목의 구체적 실천 원리인 지구 중심 사목과 연합 사목이 공간적인 개념에서 벗어나야 함을, ‘우리 반에서는’ ‘우리 구역끼리’ ‘우리 본당에서만’이라는 생각을 넘어서야 함을 깨닫게 됩니다.</p>

			<p>이러한 여정을 위해 우선 수원교구 내 모든 공동체가 중요한 문제를 결정하기에 앞서 성령의 뜻을 청하고 듣는 기도 시간을 가지고 회의에 임해야 합니다. 교회공동체의 결정이 곧 성령의 뜻을 따르는 결정이 되기 위해서는 사안에 맞는 기도를 선정하고, 교회 구성원들이 같은 지향으로 지속적으로 기도하며, 미사를 통해 성령의 도우심을 구해야 합니다. 그리고 모든 공동체가 ‘인식하기-해석하기-선택하기’라는 성령의 활동을 식별하기 위한 과정(「복음의 기쁨」 제51항)을 유념해야 하겠습니다. 먼저 ‘인식하기’란, 구체적인 현실을 파악하기 위해 공동체의 성장지표를 마련하는 것입니다. 다음으로 ‘해석하기’란, 영적 체질개선을 위해 공동체를 진단하고 평가하는 일입니다. 마지막으로 ‘선택하기’란, 성령의 활동을 파악하고 구체적인 실천을 선택하는 일입니다.</p>

			<p>통합사목을 바탕으로 한 공동체의 성장지표는 말씀의 증거생활(μαρτυρία), 축제적인 전례거행(λειτουργία), 이웃섬김(διακονία), 친교생활(κοινωνία)입니다. 친교생활은 앞선 세 가지 지표가 어느 한쪽으로 편중됨 없이 서로 고르게 연동하여 상보상생할 때에야 비로소 진정한 의미를 갖습니다. 저는 앞으로 3년간 1년 단위로 교구 구성원 모두가 친교생활을 위해 노력해 주시기를 당부드립니다.</p>

